import numpy as np
import networkx as nx
import matplotlib.pyplot as plt
import random

np.random.seed(None)
random.seed(None)

#1
def create_sbm_graph(n_nodes=200, n_blocks=4, p_in=0.15, p_out=0.008):
    block_sizes=[n_nodes//n_blocks]*n_blocks
    block_sizes[-1]+=n_nodes-sum(block_sizes)
    prob_matrix=np.full((n_blocks, n_blocks), p_out)
    np.fill_diagonal(prob_matrix, p_in)
    G=nx.stochastic_block_model(block_sizes, prob_matrix, seed=42)
    G=nx.convert_node_labels_to_integers(G)
    return G

def activation_probabilities(G, base_prob=0.1, prob_variance=0.05):
    probabilities = {}
    for u, v in G.edges():
        prob=base_prob+np.random.uniform(-prob_variance, prob_variance)
        prob=np.clip(prob, 0.05, 0.3)
        probabilities[(u, v)]=prob
        probabilities[(v, u)]=prob
    return probabilities

def icm_single_run(G, probabilities, initial_active, max_steps=100):
    active=set(initial_active)
    newly_active=set(initial_active)
    history=[active.copy()]
    for step in range(max_steps):
        if not newly_active:
            break
        next_candidates = set()
        for u in newly_active:
            for v in G.neighbors(u):
                if v not in active:
                    if random.random()<probabilities.get((u, v), 0.1):
                        next_candidates.add(v)
        newly_active=next_candidates-active
        active.update(next_candidates)
        history.append(active.copy())
    return history

def icm_multiple_runs(G, probabilities, initial_active, n_runs=100):
    final_sizes=[]
    for run in range(n_runs):
        history=icm_single_run(G, probabilities, initial_active)
        final_sizes.append(len(history[-1]))
    avg_final_size=np.mean(final_sizes)
    std_final_size=np.std(final_sizes)
    return {
        'final_sizes': final_sizes,
        'avg_final_size': avg_final_size,
        'std_final_size': std_final_size
    }

def visualize_steps(G, history_sets):
    n_steps=len(history_sets)
    pos=nx.spring_layout(G, seed=42, k=0.3)

    for step_idx, active_set in enumerate(history_sets):
        plt.figure(figsize=(10, 8))
        node_colors=[]
        for node in G.nodes():
            if node in active_set:
                node_colors.append('red')
            else:
                node_colors.append('lightgray')

        nx.draw(G, pos, node_color=node_colors,
                node_size=100, edge_color='gray', alpha=0.7,
                with_labels=False)

        plt.title(f'ШАГ {step_idx} - Активно: {len(active_set)} узлов', fontsize=14)
        plt.axis('off')

    return n_steps

