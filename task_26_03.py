def estimate_influence(G, probabilities, S, n_runs=100):
    if len(S)==0:
        return 0
    total_active=0
    for _ in range(n_runs):
        history=icm_single_run(G, probabilities, S)
        total_active+=len(history[-1])
    return total_active/n_runs

def greedy_maximization(G, probabilities, k, n_runs=50, verbose=True):
    n_nodes=G.number_of_nodes()
    selected=[]
    remaining=list(range(n_nodes))

    for i in range(k):
        best_node=None
        best_gain=-1
        if verbose:
            print(f"  Итерация {i+1}/{k}: поиск узла...")
        current_influence=estimate_influence(G, probabilities, selected, n_runs) if selected else 0

        for idx, node in enumerate(remaining):
            influence_with_node=estimate_influence(G, probabilities, selected+[node], n_runs)
            gain=influence_with_node - current_influence

            if gain>best_gain:
                best_gain=gain
                best_node=node

            if verbose and (idx + 1) % max(1, len(remaining)//10)==0:
                print(f"    Прогресс: {idx + 1}/{len(remaining)} узлов проверено", end="\r")

        if verbose:
            print(f"    Выбран узел {best_node}, прирост: {best_gain:.2f}")

        selected.append(best_node)
        remaining.remove(best_node)

    return selected

def degree_based_selection(G, k):
    degree_dict=dict(G.degree())
    sorted_nodes=sorted(degree_dict.items(), key=lambda x: x[1], reverse=True)
    selected=[node for node, degree in sorted_nodes[:k]]

    return selected

